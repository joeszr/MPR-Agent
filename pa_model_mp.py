K = 9
M = 6


def _as_column(x):
    a = np.asarray(x)
    was_row = a.ndim == 2 and a.shape[0] == 1
    return a.reshape(-1, 1), was_row


def pa_model_mp(x):
    """``y = pa_model_mp(x)``。"""
    x_col, was_row = _as_column(np.asarray(x))
    N = x_col.size

    y = np.zeros((N, 1), dtype=complex)

    x_padded = np.vstack([np.zeros((M, 1), dtype=complex), x_col])
    abs_x_sq_padded = np.abs(x_padded) ** 2

    A = COEFFS.reshape((K, M + 1), order="F").T     # (M+1) x K

    for m in range(M + 1):
        idx = slice(M - m, M - m + N)
        x_d = x_padded[idx]
        p_d = abs_x_sq_padded[idx]

        term = A[m, 0] * x_d
        poly_term = x_d
        for k in range(1, K):
            poly_term = poly_term * p_d
            term = term + A[m, k] * poly_term
        y = y + term

    return y.T if was_row else y
